const normalize = (text: string) =>
  text
    .toLowerCase()
    .replace(/[إأآا]/g, "ا")
    .replace(/ة/g, "ه")
    .replace(/ى/g, "ي")
    .replace(/[ًٌٍَُِّْـ]/g, "")
    .replace(/[؟?!،؛:.()[\]{}"']/g, " ")
    .replace(/\s+/g, " ")
    .trim();

const tokens = (text: string) =>
  normalize(text)
    .split(" ")
    .filter((token) => token.length > 1 && !STOP_WORDS.has(token));

function scoreEntry(query: string, entry: KnowledgeEntry) {
  const queryTokens = tokens(query);
  const keywords = entry.keywords.map(normalize);
  const hits = queryTokens.filter((token) =>
    keywords.some(
      (keyword) =>
        keyword === token ||
        keyword.startsWith(token) ||
        token.startsWith(keyword),
    ),
  );
  const direct = new Set(hits).size;
  const phraseBoost = normalize(query).includes(normalize(entry.title)) ? 3 : 0;
  return direct * 2 + phraseBoost;
}

function confidence(score: number) {
  return Math.min(96, Math.max(54, 54 + score * 7));
}

function greeting(query: string) {
  return /^(السلام عليكم|سلام|اهلا|أهلا|مرحبا|مرحبًا|صباح الخير|مساء الخير|شكرا|شكرًا)/i.test(
    normalize(query),
  );
}

